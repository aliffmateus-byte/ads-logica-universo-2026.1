# Exercício 14: Refatoração (While para For)
# Refatorando o exercício 13 que usava while para uma estrutura for
print("Contagem regressiva com For:")
for i in range(10, 0, -1):
    print(i)

# Explicação: O código com 'for' fica mais simples pois o controle 
# do início, fim e passo (decremento) é feito em uma única linha.

